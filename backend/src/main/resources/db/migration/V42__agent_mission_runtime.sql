CREATE TABLE agent_mission (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 session_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 request_key VARCHAR(80) NOT NULL,
 create_hash VARCHAR(64) NOT NULL,
 goal VARCHAR(1000) NOT NULL,
 mode VARCHAR(16) NOT NULL,
 external_consent BOOLEAN NOT NULL,
 stage VARCHAR(32) NOT NULL,
 state_json TEXT NOT NULL,
 business_key VARCHAR(80) NOT NULL UNIQUE,
 step_count INT NOT NULL DEFAULT 0,
 version INT NOT NULL DEFAULT 0,
 runner_token VARCHAR(40),
 lease_until TIMESTAMP,
 last_request_key VARCHAR(80),
 last_request_hash VARCHAR(64),
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(session_id) REFERENCES agent_session(id) ON DELETE CASCADE,
 FOREIGN KEY(user_id) REFERENCES app_user(id),
 UNIQUE(session_id,request_key),
 CHECK(mode IN ('LOCAL','DEEPSEEK')),
 CHECK(stage IN ('RUNNING','WAITING_INPUT','WAITING_SELECTION','WAITING_CONFIRMATION','PAUSED','FAILED','CANCELLED','DONE')),
 CHECK(step_count>=0 AND step_count<=24),
 CHECK(version>=0)
);
CREATE INDEX ix_agent_mission_owner ON agent_mission(user_id,session_id,id);
CREATE TABLE agent_mission_step (
 id BIGINT PRIMARY KEY AUTO_INCREMENT,
 mission_id BIGINT NOT NULL,
 step_number INT NOT NULL,
 action VARCHAR(40) NOT NULL,
 status VARCHAR(24) NOT NULL,
 message VARCHAR(500) NOT NULL,
 observation_json VARCHAR(2000),
 prompt_tokens INT,
 completion_tokens INT,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(mission_id) REFERENCES agent_mission(id) ON DELETE CASCADE,
 UNIQUE(mission_id,step_number),
 CHECK(step_number>=1 AND step_number<=24)
);
